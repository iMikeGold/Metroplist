class BootstrapError(RuntimeError):
    pass


def run(
    args: list[str],
    *,
    cwd: Path | None = None,
    check: bool = True,
    capture: bool = False,
) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        args,
        cwd=cwd,
        check=check,
        text=True,
        capture_output=capture,
    )


def resolve_git_root(root: Path) -> Path:
    if not shutil.which("git"):
        raise BootstrapError("git is required but was not found.")

    result = run(
        ["git", "-C", str(root), "rev-parse", "--show-toplevel"],
        capture=True,
    )
    return Path(result.stdout.strip()).resolve()


def find_nested_git_directories(paths: Iterable[Path]) -> list[Path]:
    nested: list[Path] = []
    for base in paths:
        if not base.exists():
            continue
        for current, directories, _files in os.walk(base):
            if ".git" in directories:
                nested.append(Path(current) / ".git")
                directories.remove(".git")
    return nested


def load_main_package(main_site: Path) -> dict:
    package_path = main_site / "package.json"
    if not package_path.is_file():
        raise BootstrapError(f"Missing dependency source: {package_path}")

    try:
        return json.loads(package_path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as error:
        raise BootstrapError(f"Invalid JSON in {package_path}: {error}") from error


