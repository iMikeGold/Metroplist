def validate_sql(files: dict[str, str]) -> None:
    connection = sqlite3.connect(":memory:")
    try:
        connection.executescript(files["database/migrations/0001_initial_foundation.sql"])
        connection.executescript(
            files["database/migrations/0002_indexes_and_append_only_guards.sql"]
        )
        connection.executescript(files["database/seeds/0001_reference_data.sql"])
    except sqlite3.Error as error:
        raise BootstrapError(f"Foundation SQL validation failed: {error}") from error
    finally:
        connection.close()


def preflight(expected: dict[str, str], app_site: Path) -> list[Path]:
    conflicts: list[Path] = []
    for relative, content in expected.items():
        destination = app_site / relative
        if destination.exists():
            if destination.is_dir():
                conflicts.append(destination)
                continue
            current = destination.read_text(encoding="utf-8")
            if current != content:
                conflicts.append(destination)
    return conflicts


def write_files(expected: dict[str, str], app_site: Path, dry_run: bool) -> None:
    for relative, content in sorted(expected.items()):
        destination = app_site / relative
        if destination.exists():
            print(f"unchanged  {destination}")
            continue

        print(f"create     {destination}")
        if dry_run:
            continue

        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_text(content, encoding="utf-8")

        if relative in EXECUTABLES:
            mode = destination.stat().st_mode
            destination.chmod(mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)


def main() -> int:
    parser = argparse.ArgumentParser(
        description=(
            "Create Metroplist Data Foundation and Density Explorer Release 0.1."
        )
    )
    parser.add_argument(
        "--root",
        type=Path,
        default=Path.home() / "Dev" / "Metroplist",
        help="Metroplist repository root.",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Show planned files without writing or installing.",
    )
    parser.add_argument(
        "--skip-install",
        action="store_true",
        help="Create files but do not run npm install, verification or build.",
    )
    parser.add_argument(
        "--skip-build",
        action="store_true",
        help="Install and verify without running next build.",
    )
    args = parser.parse_args()

    root = args.root.expanduser().resolve()
    main_site = root / "main-site"
    app_site = root / "app-site"

    if not root.is_dir():
        raise BootstrapError(f"Metroplist root does not exist: {root}")

    git_root = resolve_git_root(root)
    if git_root != root:
        raise BootstrapError(
            f"Expected {root} to be the Git root, but Git reports {git_root}."
        )

    nested = find_nested_git_directories([main_site, app_site])
    if nested:
        joined = "\n".join(f"  - {path}" for path in nested)
        raise BootstrapError(
            "Nested Git repositories were found. No files were changed:\n" + joined
        )

    main_package = load_main_package(main_site)
    expected = dict(FILES)
    expected["package.json"] = build_package_json(main_package)

    script_source = Path(__file__).read_text(encoding="utf-8")
    expected["scripts/bootstrap-app-site.py"] = script_source

    validate_sql(expected)

    conflicts = preflight(expected, app_site)
    if conflicts:
        joined = "\n".join(f"  - {path}" for path in conflicts)
        raise BootstrapError(
            "Existing files differ from the Release 0.1 scaffold. "
            "Nothing was overwritten:\n" + joined
        )

    print(f"Metroplist Git root: {git_root}")
    print("Nested Git directories: none")
    print(f"Target project: {app_site}")
    write_files(expected, app_site, args.dry_run)

    if args.dry_run:
        print("\nDry run complete. No files were written.")
        return 0

    if args.skip_install:
        print("\nScaffold created. Installation and checks were skipped.")
        return 0

    if not shutil.which("npm"):
        raise BootstrapError(
            "Files were created, but npm was not found. "
            "Install Node/npm and run npm install inside app-site."
        )

    print("\nInstalling exact top-level dependencies and creating package-lock.json...")
    run(["npm", "install"], cwd=app_site)

    print("\nRunning Release 0.1 verification...")
    run(["npm", "run", "verify"], cwd=app_site)

    if not args.skip_build:
        print("\nBuilding the stripped Next.js application...")
        run(["npm", "run", "build"], cwd=app_site)

    print("\nMetroplist app-site Release 0.1 foundation is ready.")
    print(f"Start locally with:\n  cd {app_site}\n  npm run dev")
    print("\nNo deployment, remote resource, commit or push was performed.")
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except BootstrapError as error:
        print(f"ERROR: {error}", file=sys.stderr)
        raise SystemExit(1)
